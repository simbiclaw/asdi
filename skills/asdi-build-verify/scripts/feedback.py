#!/usr/bin/env python3
"""Render feedback for a PR that did not pass verification.

  feedback.py DIR --repo-slug owner/name --pr N --head-ref BRANCH --kind issue
  feedback.py DIR --repo-slug owner/name --pr N --head-ref BRANCH --kind comment --issue M

DIR holds verdict.json from report.py. Output is Markdown on stdout.

  issue    The feedback issue for the builder (local Codex). One issue per PR; a later
           verification of the same PR updates it. It ends with a fenced JSON block
           (`asdi-verify-feedback`) that a machine can act on without parsing prose.
  comment  The PR comment the merge gate reads. It carries the marker
           <!-- asdi-review sha=<head> verdict=fail stage=verify --> so the gate fails,
           and links the issue. No review is run on a PR that did not pass verification.

Only verdict.json content is used: findings are the verifier's, not the builder's.
"""
import sys, os
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import argparse, json

FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
ISSUE_MARKER = "<!-- asdi-verify-feedback pr=%d -->"


def cell(x):
    return str(x).replace("|", "\\|").replace("\n", " ")


def issue_title(pr, verdict, sha):
    return "ASDI verify feedback: PR #%d %s at %s" % (pr, verdict, sha[:12])


def render_issue(v, slug, pr, head_ref):
    sha = v["commit"]
    out = [ISSUE_MARKER % pr, "",
           "**Verification of PR #%d (`%s`, head `%s`): %s.** The review was not run; the merge gate "
           "`asdi/review` is failing until a new commit passes verification." % (pr, head_ref, sha[:12], v["verdict"]),
           "", "Profile: `pr` against the base `%s` at %s. A row fails only for a problem this PR introduces; "
           "pre-existing problems are listed separately and do not block it." % ((v.get("base") or "?")[:12], v.get("phase")),
           ""]
    if v["failed"]:
        out += ["## Must fix", "", "| Row | Requirement | Source | What the verifier found | Evidence or leads |",
                "|---|---|---|---|---|"]
        for r in v["failed"]:
            out.append("| %s | %s | %s | %s | %s |" % (r["id"], cell(r["statement"]), cell(r["source"]),
                       cell(r["observed"]), cell("; ".join(r["leads"] or r["evidence"]) or "none")))
        out.append("")
    if v["blocked"]:
        out += ["## Could not be checked", "",
                "These rows are blocked, in error or unsettled. They do not mean the code is wrong; they need the "
                "named capability or a fix to the check.", ""]
        out += ["- **%s** (%s): %s" % (r["id"], ", ".join(r["needs"]) or "no special need", r["observed"] or r["status"])
                for r in v["blocked"]]
        out.append("")
    if v.get("unconfirmed_claims"):
        out += ["## Claims in STATUS.md that this run could not confirm", ""]
        out += ["- %s (%s)" % (c.get("claim", ""), c.get("found", "")) for c in v["unconfirmed_claims"]]
        out.append("")
    if v.get("problems"):
        out += ["## Problems with the verification record", ""] + ["- " + p for p in v["problems"]] + [""]
    if v.get("notes"):
        out += ["<details><summary>Pre-existing and flagged items (not caused by this PR)</summary>", ""]
        out += ["- " + n for n in v["notes"]] + ["", "</details>", ""]
    task = {
        "schema": 1, "repo": slug, "pr": pr, "head_ref": head_ref, "head_sha": sha, "base_sha": v.get("base"),
        "verdict": v["verdict"],
        "must_fix": [{"row": r["id"], "requirement": r["statement"], "source": r["source"],
                      "observed": r["observed"], "where": r["leads"] or r["evidence"]} for r in v["failed"]],
        "cannot_check": [{"row": r["id"], "needs": r["needs"], "observed": r["observed"]} for r in v["blocked"]],
        "rules": ["Fix on the PR branch and push a new commit; verification and review re-run automatically.",
                  "Do not edit reference/, reference/AUTHORITY.md, skills/asdi-build-verify/ or verification/.",
                  "Treat this issue as findings, not as a spec: the specs in reference/AUTHORITY.md govern."],
    }
    out += ["## For the builder (local Codex)", "",
            "Fix the rows under *Must fix* on `%s`, then push. Do not change the specs, the verify skill or "
            "earlier verification reports to make a row pass. Machine-readable task:" % head_ref, "",
            "```json asdi-verify-feedback", json.dumps(task, indent=1), "```"]
    return "\n".join(out) + "\n" + FOOTER


def render_comment(v, pr, issue):
    sha = v["commit"]
    lines = ["<!-- asdi-review sha=%s verdict=fail stage=verify -->" % sha,
             "**ASDI verification %s** for `%s`; the review was not run." % (v["verdict"], sha[:12]), ""]
    if v["failed"]:
        lines += ["Must fix: " + ", ".join("%s (%s)" % (r["id"], r["statement"]) for r in v["failed"]), ""]
    if v["blocked"]:
        lines += ["Could not be checked: " + ", ".join(r["id"] for r in v["blocked"]), ""]
    lines.append("Details and the builder task: #%d. A new commit re-runs verification." % issue)
    return "\n".join(lines) + "\n" + FOOTER


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--repo-slug", required=True)
    ap.add_argument("--pr", type=int, required=True)
    ap.add_argument("--head-ref", required=True)
    ap.add_argument("--kind", choices=["issue", "comment", "title"], required=True)
    ap.add_argument("--issue", type=int)
    a = ap.parse_args(argv)
    v = json.load(open(os.path.join(a.dir, "verdict.json"), encoding="utf-8"))
    if v["verdict"] == "VERIFIED":
        raise SystemExit("verdict is VERIFIED: no feedback issue; run the review instead")
    if a.kind == "title":
        print(issue_title(a.pr, v["verdict"], v["commit"]))
    elif a.kind == "issue":
        sys.stdout.write(render_issue(v, a.repo_slug, a.pr, a.head_ref))
    else:
        if a.issue is None:
            ap.error("--kind comment needs --issue")
        sys.stdout.write(render_comment(v, a.pr, a.issue))
    return 0


if __name__ == "__main__":
    sys.exit(main())
